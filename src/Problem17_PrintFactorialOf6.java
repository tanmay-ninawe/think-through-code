public class Problem17_PrintFactorialOf6 {

    public static void main(String[] args) {

        // Factorial of 6 (expected: 720)

        int num = 6;
        int result = 1;

        for (int i = 1; i <= num; i++) {

            result = result * i;
            System.out.println(result);

        }

        /*
         * ################# Logic
         * 
         * 1. scan for the numbers.
         * 2. calculate each factorial for that number
         * 
         * 
         */

    }
}
